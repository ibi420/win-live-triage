Write-Head "SECTION 4 — NETWORK CONNECTIONS & IP INTELLIGENCE" "Section 4 — Network Connections & IP Intelligence"

# Build the richest possible PID → {Name, Owner} map:
#   1. Get-Process covers most user-space processes
#   2. Win32_Process via CIM covers kernel/system PIDs (4 = System, 0 = Idle, etc.)
#   3. Well-known PIDs are hardcoded as a fallback
$pidMap   = @{}
$ownerMap = @{}

# Well-known system PIDs
$pidMap[0]  = "Idle";    $ownerMap[0]  = "SYSTEM"
$pidMap[4]  = "System";  $ownerMap[4]  = "SYSTEM"

# Populate from Get-Process (fast, covers user processes)
Get-Process -EA SilentlyContinue | ForEach-Object { $pidMap[$_.Id] = $_.Name }

# Populate from WMI — fills in kernel PIDs Get-Process misses, and gives owner info
Get-CimInstance Win32_Process -EA SilentlyContinue | ForEach-Object {
    $pid_ = $_.ProcessId
    if (-not $pidMap.ContainsKey($pid_) -or $pidMap[$pid_] -eq "?") {
        $pidMap[$pid_] = if ($_.Name) { $_.Name } else { "PID:$pid_" }
    }
    try {
        $o = $_.GetOwner()
        $ownerMap[$pid_] = if ($o.User) { "$($o.Domain)\$($o.User)".TrimStart('') } else { "SYSTEM" }
    } catch {
        $ownerMap[$pid_] = "SYSTEM"
    }
}

function Resolve-PidName {
    param([int]$Pid_)
    if ($pidMap.ContainsKey($Pid_))   { return $pidMap[$Pid_] }
    # Last resort: query WMI directly for this one PID
    $w = Get-CimInstance Win32_Process -Filter "ProcessId=$Pid_" -EA SilentlyContinue
    if ($w) { $pidMap[$Pid_] = $w.Name; return $w.Name }
    return "PID:$Pid_"
}

function Resolve-PidOwner {
    param([int]$Pid_)
    if ($ownerMap.ContainsKey($Pid_)) { return $ownerMap[$Pid_] }
    try {
        $w = Get-CimInstance Win32_Process -Filter "ProcessId=$Pid_" -EA Stop
        $o = $w.GetOwner()
        $result = if ($o.User) { "$($o.Domain)\$($o.User)".TrimStart('\') } else { "SYSTEM" }
        $ownerMap[$Pid_] = $result
        return $result
    } catch { return "SYSTEM" }
}

