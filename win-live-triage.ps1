# ─── Markdown accumulator ─────────────────────────────────────────────────────
$script:MdBuffer = [System.Text.StringBuilder]::new()

function Write-MD {
    param([string]$Line = "")
    [void]$script:MdBuffer.AppendLine($Line)
}
function Write-MD-Table-Row {
    param([string[]]$Cells)
    Write-MD ("| " + ($Cells -join " | ") + " |")
}
function Write-MD-Table-Header {
    param([string[]]$Headers)
    Write-MD-Table-Row $Headers
    Write-MD ("| " + (($Headers | ForEach-Object { "---" }) -join " | ") + " |")
}
function Flush-MD {
    $script:MdBuffer.ToString() | Out-File -FilePath $MdFile -Encoding UTF8
}
function Write-MD-Badge {
    param([string]$Severity)
    switch ($Severity) {
        'CRITICAL' { return "🔴 CRITICAL" }
        'HIGH'     { return "🟠 HIGH" }
        'MEDIUM'   { return "🟡 MEDIUM" }
        'LOW'      { return "🟢 LOW" }
        default    { return "⚪ INFO" }
    }
}

# ─── Colour / plain-text logging ─────────────────────────────────────────────
function Write-Log {
    param([string]$Text, [string]$Color = "White")
    Write-Host $Text -ForegroundColor $Color
    $Text | Out-File -FilePath $ReportFile -Append -Encoding UTF8
}
function Write-Sep { Write-Log ("─" * 76) "DarkCyan" }
function Write-Head {
    param([string]$Title, [string]$MdTitle = "")
    Write-Log ""; Write-Sep; Write-Log "  $Title" "Yellow"; Write-Sep; Write-Log ""
    Write-MD ""; Write-MD "---"; Write-MD ""
    Write-MD "## $(if ($MdTitle) { $MdTitle } else { $Title })"
    Write-MD ""
}
function Write-Alert {
    param([string]$Msg, [string]$Category = "GENERAL")
    Write-Log "  ⚠  ALERT [$Category]  $Msg" "Red"
    Write-MD "> ⚠️ **ALERT [$Category]** $Msg"
    Write-MD ""
    $script:Alerts++
}
function Add-IOC {
    param([string]$Type,[string]$Value,[string]$Context,[string]$Severity)
    $IOCs.Add([PSCustomObject]@{ Type=$Type; Value=$Value; Context=$Context; Severity=$Severity; Time=(Get-Date) })
}

